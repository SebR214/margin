#!/usr/bin/env python3
"""Build the site that GitHub Pages serves (SEB-436). No model, stdlib only.

Until 2 Nov the generated pages (the baked <noscript> blocks, the .md twins, llms.txt, sitemap.xml, robots.txt, 404.html and one
page per country) were committed to main in the same push as the prices. A page that grew (SEB-431 stacked its block on every run
and reached 114 MB) made GitHub refuse the push, and the prices went with it. Now git holds the data and the templates. This
script builds the rest on the runner, after the data is committed, and puts the whole site in _site/ for
actions/upload-pages-artifact and actions/deploy-pages.

    python3 tools/build_site.py                  # build the pages here, then collect the site into _site/
    python3 tools/build_site.py --check-tracked  # fail if git holds a generated file (used by checks.yml)
    python3 tools/build_site.py --strip          # take the baked blocks back out of the page templates after a local build
    python3 tools/build_site.py --self-test

What is built, in order: the machine view (tools/emit_markdown.py: the .md twins, llms.txt, the country pages, sitemap.xml,
robots.txt, 404.html) and the pages that show what they draw with scripts off (tools/bake_pages.py). A step that fails is run
once more. If it fails again nothing is collected and the script exits 1: a half-built site would lose pages (the country
pages exist only in the build), so the site stays on the last good deploy and the step goes red.

_site/ holds every tracked file plus the generated ones, linked rather than copied. The daily raw ad folders (data/p2p_ads/,
data/p2p_ads_sellers/, data/p2p_offers/, data/depth/, data/p2p_board_ads/) and the hourly receipt folders (data/corridor_receipts/,
data/provider_receipts/) are left out: nothing links them, they grow about 50 MB a day together, and Pages sites are limited to 1 GB. The closed files (data/p2p_ads.csv and the rest) are listed in llms.txt, so they stay.
"""
import os
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE = "_site"

GENERATED_FILES = {"index.md", "countries.md", "sending-money.md", "sources.md", "how-it-works.md", "how-it-was-built.md",
                   "machine-room.md", "llms.txt", "sitemap.xml", "robots.txt", "404.html"}
GENERATED_DIRS = ("country/", "finding/")
LEFT_OUT = ("data/p2p_ads/", "data/p2p_ads_sellers/", "data/p2p_offers/", "data/depth/", "data/p2p_board_ads/",
            # One file per route per hour, about 25 MB a day between them. No page opens them (the overlay that would is not
            # wired to any page), the number audit reads them from the repo, and they took the site past 1 GB on 8 Nov.
            "data/corridor_receipts/", "data/provider_receipts/")
BAKED_PAGES = ("index.html", "countries.html", "sending-money.html", "sources.html", "events.html", "how-it-works.html",
               "how-it-was-built.html", "research.html", "research-capital-controls.html", "research-source-pairs.html")
BEGIN = "<!-- bake:begin -->"
STEPS = [("machine view", ["tools/emit_markdown.py"]), ("pages that draw", ["tools/bake_pages.py"])]
MUST_EXIST = ("index.html", "404.html", "sitemap.xml", "robots.txt", "llms.txt", "index.md", "data/index_latest.json")


def is_generated(path):
    return path in GENERATED_FILES or path.startswith(GENERATED_DIRS)


def left_out(path):
    return path.startswith(LEFT_OUT)


def tracked(root):
    out = subprocess.run(["git", "ls-files", "-z"], cwd=root, capture_output=True, check=True).stdout.decode()
    return [p for p in out.split("\0") if p]


def generated_present(root):
    found = set()
    for p in GENERATED_FILES:
        if os.path.isfile(os.path.join(root, p)):
            found.add(p)
    for d in GENERATED_DIRS:
        for base, _, files in os.walk(os.path.join(root, d)):
            for f in files:
                found.add(os.path.relpath(os.path.join(base, f), root))
    return found


def check_tracked(root=HERE):
    """Problems with what git holds: a generated file, or a page that still carries its baked block. [] when it is right."""
    bad = []
    for p in tracked(root):
        if is_generated(p):
            bad.append("%s is generated by the site build and must not be in git" % p)
        elif p in BAKED_PAGES and os.path.isfile(os.path.join(root, p)):
            if BEGIN in open(os.path.join(root, p), encoding="utf-8").read():
                bad.append("%s carries a baked block, it belongs only in the built site" % p)
    return bad


def strip(root=HERE):
    """Remove the baked block from every page template. The build writes it into the checkout; a checkout that is about to be committed must not carry it."""
    sys.path.insert(0, os.path.join(root, "tools"))
    import bake_pages
    n = 0
    for p in BAKED_PAGES:
        full = os.path.join(root, p)
        if os.path.isfile(full):
            text = open(full, encoding="utf-8").read()
            new = bake_pages.BLOCK.sub("", text)
            if new != text:
                open(full, "w", encoding="utf-8").write(new)
                n += 1
    return n


def assemble(root, site):
    """Link every tracked file and every generated file into `site`, minus what is left out. Returns the file count."""
    if os.path.isdir(site):
        shutil.rmtree(site)
    paths = {p for p in tracked(root) if os.path.isfile(os.path.join(root, p))} | generated_present(root)
    n = 0
    for p in sorted(paths):
        if left_out(p) or p.startswith(".github/"):
            continue
        dst = os.path.join(site, p)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        src = os.path.join(root, p)
        try:
            os.link(src, dst)
        except OSError:
            shutil.copy2(src, dst)
        n += 1
    return n


def problems(root, site):
    """What is wrong with a collected site. [] when it is right."""
    bad = []
    for p in MUST_EXIST:
        if not os.path.isfile(os.path.join(site, p)):
            bad.append("%s is missing from the site" % p)
    cdir = os.path.join(root, "data", "countries")
    if os.path.isdir(cdir):
        for f in sorted(os.listdir(cdir)):
            ccy = f[:-5]
            if f.endswith(".json") and ccy.isalpha() and ccy.isupper():
                if not os.path.isfile(os.path.join(site, "country", ccy.lower(), "index.html")):
                    bad.append("country/%s/index.html is missing from the site" % ccy.lower())
    for p in BAKED_PAGES:
        full = os.path.join(site, p)
        if os.path.isfile(full):
            n = open(full, encoding="utf-8").read().count(BEGIN)
            if n != 1:
                bad.append("%s carries %d baked blocks, it must carry exactly one" % (p, n))
        elif os.path.isfile(os.path.join(root, p)):
            bad.append("%s is missing from the site" % p)
    for base, _, files in os.walk(site):
        for f in files:
            if os.path.getsize(os.path.join(base, f)) >= 100 * 1024 * 1024:   # the closed data/p2p_ads_sellers.csv is 99.6 MB and is served
                bad.append("%s is 100 MB or more" % os.path.relpath(os.path.join(base, f), site))
    return bad


MB = 1024 * 1024
WARN_AT, FAIL_AT = 900 * MB, 1000 * MB          # Pages sites are limited to 1 GB


def site_size(site):
    return sum(os.path.getsize(os.path.join(b, f)) for b, _, fs in os.walk(site) for f in fs)


def biggest(site, n=3):
    """The n largest folders under data/ (and their MB), for the message that says why the site is too big."""
    sizes = {}
    for entry in sorted(os.listdir(os.path.join(site, "data"))) if os.path.isdir(os.path.join(site, "data")) else []:
        full = os.path.join(site, "data", entry)
        sizes["data/" + entry] = site_size(full) if os.path.isdir(full) else os.path.getsize(full)
    return ["%s %d MB" % (k, v // MB) for k, v in sorted(sizes.items(), key=lambda kv: -kv[1])[:n]]


def run_step(name, argv, root):
    for attempt in (1, 2):
        r = subprocess.run([sys.executable] + argv, cwd=root)
        if r.returncode == 0:
            return True
        print("::warning::%s failed (exit %d)%s" % (name, r.returncode, ", running it once more" if attempt == 1 else ""), flush=True)
    return False


def build(root=HERE, site=None):
    site = site or os.path.join(root, SITE)
    failed = [name for name, argv in STEPS if not run_step(name, argv, root)]
    if failed:
        print("::error::the site was not built (%s failed twice), so nothing is deployed and the site stays on its last good build" % ", ".join(failed))
        return 1
    n = assemble(root, site)
    bad = problems(root, site)
    if bad:
        print("::error::the built site is wrong, so nothing is deployed:\n  " + "\n  ".join(bad))
        shutil.rmtree(site, ignore_errors=True)
        return 1
    size = site_size(site)
    if size >= FAIL_AT:
        print("::error::the site is %d MB, over the 1 GB GitHub Pages allows (%s), so nothing is deployed" % (size // MB, ", ".join(biggest(site))))
        shutil.rmtree(site, ignore_errors=True)
        return 1
    if size >= WARN_AT:
        print("::warning::the site is %d MB and GitHub Pages stops at 1 GB. Largest: %s" % (size // MB, ", ".join(biggest(site))))
    print("site built: %d files, %.0f MB, in %s/" % (n, size / MB, SITE))
    return 0


def self_test():
    with tempfile.TemporaryDirectory() as d:
        def put(p, text="x\n"):
            full = os.path.join(d, p)
            os.makedirs(os.path.dirname(full) or d, exist_ok=True)
            open(full, "w").write(text)
        subprocess.run(["git", "init", "-q"], cwd=d, check=True)
        for p in ("index.html", "countries.html", "js/home.js", "data/index_latest.json", "data/countries/AED.json",
                  "data/p2p_ads.csv", "data/p2p_ads/2026-11-02.csv", "data/depth/2026-11-02.csv", ".github/workflows/x.yml"):
            put(p)
        subprocess.run(["git", "add", "-A"], cwd=d, check=True)
        assert check_tracked(d) == [], check_tracked(d)
        # generated files in the tree are not tracked, but they are collected
        for p in ("index.md", "llms.txt", "sitemap.xml", "robots.txt", "404.html", "country/aed/index.html", "country/AED.md", "finding/a.md"):
            put(p)
        put("scratch.txt")                                   # untracked and not generated: not published
        site = os.path.join(d, SITE)
        n = assemble(d, site)
        have = {os.path.relpath(os.path.join(b, f), site) for b, _, fs in os.walk(site) for f in fs}
        assert "scratch.txt" not in have and ".github/workflows/x.yml" not in have, have
        assert "data/p2p_ads/2026-11-02.csv" not in have and "data/depth/2026-11-02.csv" not in have, "daily raw folders are left out"
        assert "data/p2p_ads.csv" in have and "country/aed/index.html" in have and "llms.txt" in have and "js/home.js" in have, have
        assert n == len(have)
        assert site_size(site) > 0 and biggest(site, 1)[0].startswith("data/"), biggest(site)
        # the checks on the collected site
        bad = problems(d, site)
        assert any("countries.html carries 0 baked" in b for b in bad) and any("index.html carries 0 baked" in b for b in bad), bad
        for p in ("index.html", "countries.html"):
            put(p, "<body>x\n%s\n<noscript>y</noscript>\n</body>\n" % BEGIN)
        assemble(d, site)
        assert problems(d, site) == [], problems(d, site)
        os.remove(os.path.join(d, "country", "aed", "index.html"))
        assemble(d, site)
        assert problems(d, site) == ["country/aed/index.html is missing from the site"], problems(d, site)
        # a generated file in git, or a baked block in a tracked page, is caught
        put("country/aed/index.html")
        subprocess.run(["git", "add", "-f", "country/aed/index.html", "llms.txt"], cwd=d, check=True)
        subprocess.run(["git", "add", "-f", "index.html"], cwd=d, check=True)
        bad = check_tracked(d)
        assert len(bad) == 4 and any("llms.txt is generated" in b for b in bad) and any("index.html carries a baked block" in b for b in bad), bad
    with tempfile.TemporaryDirectory() as d:
        os.makedirs(os.path.join(d, "tools"))
        shutil.copy(os.path.join(HERE, "tools", "bake_pages.py"), os.path.join(d, "tools"))
        shutil.copy(os.path.join(HERE, "tools", "gate_common.py"), os.path.join(d, "tools"))
        page = "<html><body>x\n</body></html>\n"
        open(os.path.join(d, "index.html"), "w").write(page.replace("</body>", "%s\n<noscript>y</noscript>\n<!-- bake:end -->\n</body>" % BEGIN))
        assert strip(d) == 1 and open(os.path.join(d, "index.html")).read() == page and strip(d) == 0, "strip returns the template to what it was"
    assert is_generated("country/AED.md") and is_generated("sitemap.xml") and not is_generated("country.html") and not is_generated("CLAUDE.md")
    print("build_site self-test: ok")
    return 0


def main(argv):
    if "--self-test" in argv:
        return self_test()
    if "--strip" in argv:
        print("stripped the baked block from %d pages" % strip())
        return 0
    if "--check-tracked" in argv:
        bad = check_tracked()
        for b in bad:
            print("::error::" + b)
        print("generated files in git: %s" % ("none" if not bad else "%d problems" % len(bad)))
        return 1 if bad else 0
    return build()


if __name__ == "__main__":
    sys.exit(main(sys.argv))
